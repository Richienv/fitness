const BY_CODE = new Map<string, BarcodeProduct>(ENTRIES.map((e) => [e.code, e]));

export function lookupIndoBarcode(rawCode: string): BarcodeProduct | null {
  const code = rawCode.replace(/\s/g, "");
  if (!code) return null;
  const exact = BY_CODE.get(code);
  if (exact) return exact;
  if (code.length === 12) return BY_CODE.get(`0${code}`) ?? null;
  if (code.length === 13 && code.startsWith("0")) return BY_CODE.get(code.slice(1)) ?? null;
  return null;
}

export function indoBarcodeCount(): number {
  return ENTRIES.length;
}
